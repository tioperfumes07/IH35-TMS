#!/usr/bin/env node
/**
 * Exhaustive driver-picker inventory (owner GO 2026-07-22 #5).
 * Scans apps/frontend/src for surfaces that select/create drivers.
 * Writes docs/trackers/DRIVER-PICKER-SYSTEM-AUDIT-2026-07-22.md
 *
 * Classification:
 *   CANONICAL_CREATE — CreateDriverModal (correct nested +Create target)
 *   HAS_PICKER_NO_CREATE — selects driver, no nested +Create
 *   INLINE_PICKER — InlineDriverPicker / QuickAssign style
 *   FILTER_ONLY — report/filter driver dropdown (create optional)
 *   TEST — test/fixture only
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "apps/frontend/src");
const OUT = path.join(ROOT, "docs/trackers/DRIVER-PICKER-SYSTEM-AUDIT-2026-07-22.md");

const SKIP_DIR = new Set(["node_modules", "dist", "coverage", ".git"]);

function walk(dir, acc = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIR.has(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, acc);
    else if (/\.(tsx|ts|jsx|js)$/.test(ent.name)) acc.push(p);
  }
  return acc;
}

function rel(p) {
  return path.relative(ROOT, p).replaceAll("\\", "/");
}

const files = walk(SRC);
const rows = [];

for (const file of files) {
  const text = fs.readFileSync(file, "utf8");
  const r = rel(file);
  const isTest = /\.(test|spec)\.|\/__tests__\//.test(r);

  const hasCreateModal = /CreateDriverModal/.test(text);
  const hasInlinePicker = /InlineDriverPicker/.test(text);
  const hasListDrivers = /listDrivers\s*\(/.test(text);
  const hasDriverIdField =
    /\bdriver_id\b|\bdriverId\b|assigned_primary_driver|assigned_secondary_driver|respondent_driver|relatedDriver/.test(
      text
    );
  const hasSelectNearDriver =
    /(SelectCombobox|Combobox)[\s\S]{0,400}driver|driver[\s\S]{0,400}(SelectCombobox|Combobox)/i.test(text);
  const hasCreateKindDriver = /createKind\s*=\s*["']driver["']/.test(text);
  const hasReferenceSelectDriver = /ReferenceSelect[\s\S]{0,200}driver|createKind=["']driver["']/.test(text);

  if (
    !hasCreateModal &&
    !hasInlinePicker &&
    !hasListDrivers &&
    !(hasDriverIdField && hasSelectNearDriver) &&
    !hasCreateKindDriver
  ) {
    continue;
  }

  let verdict = "HAS_PICKER_NO_CREATE";
  let notes = [];
  if (isTest) verdict = "TEST";
  else if (hasCreateModal) {
    verdict = "CANONICAL_CREATE";
    notes.push("uses CreateDriverModal");
  } else if (hasInlinePicker) {
    verdict = "INLINE_PICKER";
    notes.push("InlineDriverPicker / assign chrome");
  } else if (hasListDrivers && !hasSelectNearDriver && !hasDriverIdField) {
    verdict = "FILTER_ONLY";
    notes.push("listDrivers without obvious select UI in same file — verify manually");
  }

  if (hasCreateKindDriver || hasReferenceSelectDriver) {
    notes.push("has createKind=driver / ReferenceSelect driver wiring");
  }
  if (hasListDrivers) notes.push("listDrivers()");
  if (hasSelectNearDriver) notes.push("SelectCombobox/Combobox near driver");

  rows.push({
    path: r,
    verdict,
    createModal: hasCreateModal,
    listDrivers: hasListDrivers,
    selectNear: hasSelectNearDriver,
    inline: hasInlinePicker,
    createKindDriver: hasCreateKindDriver,
    notes: notes.join("; ") || "—",
  });
}

rows.sort((a, b) => a.verdict.localeCompare(b.verdict) || a.path.localeCompare(b.path));

const counts = {};
for (const row of rows) counts[row.verdict] = (counts[row.verdict] || 0) + 1;

const moneyPaths = rows.filter(
  (r) =>
    !r.path.includes("__tests__") &&
    !r.path.includes(".test.") &&
    /(accounting|cash-advance|expenses|bill|fine|settlement|factoring|banking)/i.test(r.path)
);
const dispatchPaths = rows.filter(
  (r) => !r.path.includes("test") && /dispatch|BookLoad|QuickAssign|InlineDriver/i.test(r.path)
);
const safetyPaths = rows.filter(
  (r) => !r.path.includes("test") && /safety|Fine|Complaint|Incident/i.test(r.path)
);

const md = `# DRIVER PICKER — SYSTEM-WIDE AUDIT (2026-07-22)

**Owner GO:** createKind/driver nested +Create = **Yes** — canonical chrome = \`CreateDriverModal\` only (drawer shell when parent is drawer).  
**This file:** exhaustive static inventory of \`apps/frontend/src\` (generated by \`scripts/inventory-driver-pickers.mjs\`).  
**Not yet built:** ReferenceSelect \`createKind="driver"\` wiring — inventory first.

## Headline

| Verdict | Count |
|---------|------:|
${Object.entries(counts)
  .sort()
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}
| **TOTAL hits** | **${rows.length}** |

\`createKind="driver"\` on ReferenceSelect today: **${rows.some((r) => r.createKindDriver) ? "PRESENT" : "ABSENT (expected — kind not implemented yet)"}**

## Recommended build waves (after this audit)

1. **PLUS-DRIVER-MONEY** — money surfaces still \`HAS_PICKER_NO_CREATE\`: Bill / Expense / Cash advance / Fine / settlements that pick a driver without nested +Create.  
2. **PLUS-DRIVER-DISPATCH** — BookLoad / InlineDriverPicker / QuickAssign.  
3. **PLUS-DRIVER-SAFETY** — Complaints / Fine / Incidents cluster.  
4. **PLUS-DRIVER-OTHER** — UserDetail, AutoDeductionPolicies, reports filters (FILTER_ONLY may stay create-optional).

Guard (future PR): fail if covered money/dispatch surfaces use bare \`SelectCombobox\` for driver without \`CreateDriverModal\` / \`createKind="driver"\`.

## Money / settlements / advances (priority)

| Path | Verdict | Notes |
|------|---------|-------|
${moneyPaths.map((r) => `| \`${r.path}\` | ${r.verdict} | ${r.notes} |`).join("\n") || "| — | — | none |"}

## Dispatch / assign

| Path | Verdict | Notes |
|------|---------|-------|
${dispatchPaths.map((r) => `| \`${r.path}\` | ${r.verdict} | ${r.notes} |`).join("\n") || "| — | — | none |"}

## Safety

| Path | Verdict | Notes |
|------|---------|-------|
${safetyPaths.map((r) => `| \`${r.path}\` | ${r.verdict} | ${r.notes} |`).join("\n") || "| — | — | none |"}

## Full inventory

| Path | Verdict | CreateModal | listDrivers | Select~driver | Notes |
|------|---------|:-----------:|:-----------:|:-------------:|-------|
${rows
  .map(
    (r) =>
      `| \`${r.path}\` | ${r.verdict} | ${r.createModal ? "Y" : ""} | ${r.listDrivers ? "Y" : ""} | ${r.selectNear ? "Y" : ""} | ${r.notes} |`
  )
  .join("\n")}

## Method

- Walked all \`.ts\`/\`.tsx\` under \`apps/frontend/src\`.
- Hit if file references \`CreateDriverModal\`, \`InlineDriverPicker\`, \`listDrivers(\`, or driver-ish field names near Combobox/SelectCombobox.
- False positives possible on FILTER_ONLY / shared hooks — wave PRs must open each file before migrating.
- Regenerated: \`node scripts/inventory-driver-pickers.mjs\`
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`Wrote ${rel(OUT)} (${rows.length} rows)`);
