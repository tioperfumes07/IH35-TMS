#!/usr/bin/env node
/**
 * GUARD: BANK-00 — PERMANENT-FIX §1. No Banking PR may land without a ranked BANK-F##
 * FAIL id bound to docs/module-completion/banking.json.
 *
 * Asserts:
 *   1. docs/module-completion/banking.json carries `ranked_fail_registry.rows` enumerating
 *      BANK-F01..BANK-F07 + BANK-P01 (Rule 21 — M grows, never frozen below live leaves).
 *   2. Every row's bound_items[] cites an id that actually exists in banking.json items[]
 *      (no FAIL row pointing at a phantom manifest entry).
 *   3. banking.json items[].length (M) is at least the current live-leaf floor (13) — M can
 *      grow (Rule 21/24), but is never frozen below the live leaf count to hide leaves.
 *   4. docs/module-completion/banking.md literally renders every registry row id (defense in
 *      depth against a hand-edit of the .md drifting from the .json source of truth — the .md
 *      is normally machine-generated by scripts/verify-module-completion.mjs --write-md).
 *
 * Does NOT flip FAIL→PASS. Does NOT touch Neon. Does NOT re-derive seed counts — this guard
 * only checks that the registry is PUBLISHED and BOUND; scripts/verify-module-completion.mjs
 * (step 1431) is what checks each item's own status shape.
 *
 *   node scripts/verify-banking-fail-registry.mjs
 *   node scripts/verify-banking-fail-registry.mjs --selftest
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LABEL = "verify-banking-fail-registry";
const JSON_PATH = path.join(ROOT, "docs/module-completion/banking.json");
const MD_PATH = path.join(ROOT, "docs/module-completion/banking.md");

// PERMANENT-FIX §1 floor at the time this guard was written (BANK-00, 2026-07-25). M may grow
// as new leaves/FAILs are enumerated (Rule 21) — it must never be frozen BELOW this many live
// leaves just to make a scoreboard look smaller.
const MIN_M = 13;

export const REQUIRED_ROW_IDS = [
  "BANK-F01",
  "BANK-F02",
  "BANK-F03",
  "BANK-F04",
  "BANK-F05",
  "BANK-F06",
  "BANK-F07",
  "BANK-P01",
];

/**
 * Pure contract check over in-memory { json, mdText } — never mutates disk. The selftest below
 * feeds this deliberately-mutated copies of the REAL banking.json/banking.md content so every
 * assertion is exercised against the actual registry shape, not a synthetic fixture that could
 * drift from what the real files look like.
 */
export function contractErrors({ json, mdText }) {
  const errors = [];
  let data;
  try {
    data = typeof json === "string" ? JSON.parse(json) : json;
  } catch (e) {
    return [`banking.json is not valid JSON: ${e.message}`];
  }

  const items = Array.isArray(data.items) ? data.items : [];
  const itemIds = new Set(items.map((it) => it.id));
  const rows = Array.isArray(data.ranked_fail_registry?.rows) ? data.ranked_fail_registry.rows : [];

  if (!rows.length) {
    errors.push(
      "banking.json missing ranked_fail_registry.rows — PERMANENT-FIX §1 (BANK-00) unpublished"
    );
    return errors;
  }

  const rowIds = new Set(rows.map((r) => r.id));
  for (const required of REQUIRED_ROW_IDS) {
    if (!rowIds.has(required)) {
      errors.push(`ranked_fail_registry missing required row ${required} (PERMANENT-FIX §1)`);
    }
  }

  for (const row of rows) {
    const bound = Array.isArray(row.bound_items) ? row.bound_items : [];
    if (!bound.length) {
      errors.push(`${row.id}: bound_items[] empty — FAIL row cites no banking.json item`);
      continue;
    }
    for (const boundId of bound) {
      if (!itemIds.has(boundId)) {
        errors.push(
          `${row.id}: bound_items cites "${boundId}" which does not exist in banking.json items[]`
        );
      }
    }
  }

  if (items.length < MIN_M) {
    errors.push(
      `banking.json items[] has ${items.length} leaves — below the live floor of ${MIN_M} ` +
        `(M frozen below live leaves — Rule 21 violation)`
    );
  }

  if (typeof mdText === "string") {
    if (!/##\s*RANKED\s+BANKING\s+FAIL\s+LIST/i.test(mdText)) {
      errors.push("banking.md missing '## RANKED BANKING FAIL LIST' section");
    }
    for (const required of REQUIRED_ROW_IDS) {
      if (!mdText.includes("`" + required + "`")) {
        errors.push(`banking.md ranked list missing row ${required}`);
      }
    }
  }

  return errors;
}

function loadReal() {
  const json = JSON.parse(fs.readFileSync(JSON_PATH, "utf8"));
  const mdText = fs.readFileSync(MD_PATH, "utf8");
  return { json, mdText };
}

/**
 * Mutates in-memory copies of the REAL banking.json/banking.md content (never writes to disk)
 * and asserts each planted defect is caught, then asserts the untouched real registry is
 * NOT flagged. One case per assertion (Rule 16/17 style).
 */
function selftest() {
  const { json, mdText } = loadReal();

  const baseline = contractErrors({ json, mdText });
  if (baseline.length) {
    console.error(`${LABEL} --selftest FAIL: complete real registry flagged (expected 0 errors):`);
    for (const e of baseline) console.error(`  - ${e}`);
    process.exit(1);
  }

  // Case 1: drop a FAIL row (BANK-F01) out of the REAL banking.md text — in-memory only.
  const mdMissingRow = mdText
    .split("\n")
    .filter((line) => !line.includes("`BANK-F01`"))
    .join("\n");
  if (mdMissingRow === mdText) {
    console.error(
      `${LABEL} --selftest FAIL: BANK-F01 row not found in real banking.md — selftest fixture stale, ` +
        `re-run node scripts/verify-module-completion.mjs --write-md`
    );
    process.exit(1);
  }
  const mdMissingErrors = contractErrors({ json, mdText: mdMissingRow });
  if (!mdMissingErrors.some((e) => e.includes("BANK-F01"))) {
    console.error(`${LABEL} --selftest FAIL: dropped BANK-F01 row from banking.md not flagged`);
    process.exit(1);
  }

  // Case 2: drop BANK-F01 out of the REAL banking.json ranked_fail_registry.rows — in-memory.
  const jsonMissingRow = {
    ...json,
    ranked_fail_registry: {
      ...json.ranked_fail_registry,
      rows: json.ranked_fail_registry.rows.filter((r) => r.id !== "BANK-F01"),
    },
  };
  const jsonMissingErrors = contractErrors({ json: jsonMissingRow, mdText });
  if (!jsonMissingErrors.some((e) => e.includes("BANK-F01"))) {
    console.error(`${LABEL} --selftest FAIL: dropped BANK-F01 row from banking.json rows not flagged`);
    process.exit(1);
  }

  // Case 3: a bound_items id that does not exist in items[] must be flagged (phantom bind).
  const jsonPhantomBind = {
    ...json,
    ranked_fail_registry: {
      ...json.ranked_fail_registry,
      rows: json.ranked_fail_registry.rows.map((r) =>
        r.id === "BANK-F02" ? { ...r, bound_items: ["BANK-DOES-NOT-EXIST"] } : r
      ),
    },
  };
  const phantomErrors = contractErrors({ json: jsonPhantomBind, mdText });
  if (!phantomErrors.some((e) => e.includes("BANK-DOES-NOT-EXIST"))) {
    console.error(`${LABEL} --selftest FAIL: phantom bound_items id not flagged`);
    process.exit(1);
  }

  // Case 4: M frozen below the live floor (13) must be flagged, even if rows still cite ids.
  const jsonFrozenM = { ...json, items: json.items.slice(0, 5) };
  const frozenErrors = contractErrors({ json: jsonFrozenM, mdText });
  if (!frozenErrors.some((e) => e.includes("below the live floor"))) {
    console.error(`${LABEL} --selftest FAIL: M frozen below live floor not flagged`);
    process.exit(1);
  }

  // Case 5: the untouched, complete real registry must NOT be flagged by any of the above shapes.
  const finalClean = contractErrors({ json, mdText });
  if (finalClean.length) {
    console.error(`${LABEL} --selftest FAIL: complete registry flagged after running mutation cases:`);
    for (const e of finalClean) console.error(`  - ${e}`);
    process.exit(1);
  }

  console.log(
    `${LABEL}: --selftest PASS (5 cases: dropped .md row, dropped .json row, phantom bind, ` +
      `frozen M, clean-registry-not-flagged)`
  );
}

// Guarded by IS_MAIN so importing { contractErrors, REQUIRED_ROW_IDS } from another script/test
// (e.g. to reproduce the pre-fix defect against origin/main's copy of banking.json/.md) never
// triggers this module's own disk read + process.exit side effects.
const IS_MAIN = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (IS_MAIN && process.argv.includes("--selftest")) {
  selftest();
  process.exit(0);
}

if (IS_MAIN) {
  const { json, mdText } = loadReal();
  const errors = contractErrors({ json, mdText });
  if (errors.length) {
    console.error(`${LABEL}: FAIL`);
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }
  console.log(
    `${LABEL}: PASS — ranked BANK-F01..F07 + BANK-P01 published, bound to ${json.items.length} live ` +
      `banking.json leaves (PERMANENT-FIX §1)`
  );
  process.exit(0);
}
