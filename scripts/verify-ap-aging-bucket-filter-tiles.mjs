#!/usr/bin/env node
/**
 * verify-ap-aging-bucket-filter-tiles — A5 item 4 (ROUND 21.1 CC-1 open queue)
 *
 * AccountsPayableAgingPage's aging-bucket TOTAL strip must double as a click-to-filter control:
 * "the tile IS the filter" (owner wording, relayed via the Lead directive). One clickable tile per
 * REAL bucket (Current / 1-30 / 31-60 / 61-90 / 91+) — never a "Total" tile, since Total is a sum,
 * not a bucket a vendor can be filtered into. Clicking a tile narrows the vendor grid (both the By
 * Vendor and By Vendor Type views share one row list) to vendors carrying a nonzero balance in
 * that bucket; the tile's own dollar figure stays the full type-filtered sum regardless of which
 * tile is active, so the number a user just clicked never appears to move. A read-only, additive,
 * BEHAVIOR-ONLY change (no restyle) — reuses this file's own existing slate/red palette tokens.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = "apps/frontend/src/pages/accounting/AccountsPayableAgingPage.tsx";
const TEST = "apps/frontend/src/pages/accounting/__tests__/AccountsPayableAgingPage.bucketTiles.test.tsx";

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

export function checkSource(src, label = "AccountsPayableAgingPage") {
  assert(src.includes('data-testid="ap-aging-bucket-filter-tiles"'), `${label}: must render the bucket-filter tile strip`);
  // Tiles are generated by mapping BUCKET_FILTER_KEYS, one data-testid={`ap-aging-bucket-tile-${k}`}
  // per key — the exact-5-buckets assert below is what actually pins Current/1-30/31-60/61-90/91+
  // (and excludes "total") into existence; this just confirms the map target is that template.
  assert(/data-testid=\{`ap-aging-bucket-tile-\$\{k\}`\}/.test(src), `${label}: each mapped bucket must render data-testid="ap-aging-bucket-tile-<key>"`);
  assert(/BUCKET_FILTER_KEYS\s*=\s*\[\s*"current",\s*"d1_30",\s*"d31_60",\s*"d61_90",\s*"d90_plus",?\s*\]/.test(src), `${label}: BUCKET_FILTER_KEYS must be exactly the 5 real buckets (no "total")`);
  assert(/aria-pressed=\{active\}/.test(src), `${label}: each tile must expose its active state via aria-pressed`);
  assert(/setBucketFilter\(active \? "all" : k\)/.test(src), `${label}: clicking the active tile again must clear the filter (toggle, not one-way)`);
  assert(
    /bucketFilter === "all" \? typeFiltered : typeFiltered\.filter\(\(v\) => amount\(v, bucketFilter\) !== 0\)/.test(src),
    `${label}: vendorTableRows must filter typeFiltered down to vendors with a nonzero amount in the selected bucket`,
  );
  assert(/vendorTotals = useMemo\(\(\) => typeFiltered\.reduce\(addBuckets, emptyBuckets\(\)\), \[typeFiltered\]\)/.test(src), `${label}: tile dollar figures must read from the full type-filtered total (vendorTotals), not the bucket-narrowed rows — a tile's own number must not move when it is clicked`);
  assert(src.includes('data-testid="ap-aging-bucket-tile-clear"'), `${label}: must offer an explicit Clear affordance once a bucket is active`);
}

function checkTestFileExists() {
  assert(fs.existsSync(path.join(ROOT, TEST)), `Missing regression test: ${TEST}`);
  const testSrc = fs.readFileSync(path.join(ROOT, TEST), "utf8");
  assert(/narrows the by-vendor grid/i.test(testSrc), `${TEST}: must assert the click-to-filter narrowing behavior`);
  assert(/restores every vendor/i.test(testSrc), `${TEST}: must assert the toggle-off / Clear behavior`);
}

function selftest() {
  const good = fs.readFileSync(path.join(ROOT, PAGE), "utf8");
  checkSource(good);
  checkTestFileExists();

  // Mutation 1: drop the tile strip entirely — must fail.
  const noTiles = good.replace(/data-testid="ap-aging-bucket-filter-tiles"/, "data-testid=\"removed\"");
  let noTilesCaught = false;
  try {
    checkSource(noTiles, "mut-no-tiles");
  } catch {
    noTilesCaught = true;
  }
  assert(noTilesCaught, "selftest: expected FAIL when the bucket-filter tile strip is removed");

  // Mutation 2: widen BUCKET_FILTER_KEYS to include "total" — must fail (Total is not a bucket).
  const totalTile = good.replace(
    'const BUCKET_FILTER_KEYS = ["current", "d1_30", "d31_60", "d61_90", "d90_plus"] as const;',
    'const BUCKET_FILTER_KEYS = ["current", "d1_30", "d31_60", "d61_90", "d90_plus", "total"] as const;',
  );
  assert(totalTile !== good, "selftest: BUCKET_FILTER_KEYS literal not found to mutate — guard regex is stale");
  let totalTileCaught = false;
  try {
    checkSource(totalTile, "mut-total-tile");
  } catch {
    totalTileCaught = true;
  }
  assert(totalTileCaught, "selftest: expected FAIL when a Total bucket-filter tile is added");

  // Mutation 3: make the tile a one-way filter (no toggle-off) — must fail.
  const oneWay = good.replace('onClick={() => setBucketFilter(active ? "all" : k)}', 'onClick={() => setBucketFilter(k)}');
  assert(oneWay !== good, "selftest: toggle onClick literal not found to mutate — guard regex is stale");
  let oneWayCaught = false;
  try {
    checkSource(oneWay, "mut-one-way");
  } catch {
    oneWayCaught = true;
  }
  assert(oneWayCaught, "selftest: expected FAIL when a tile can't be clicked again to clear the filter");

  // Mutation 4: make the tile's own dollar figure read from the bucket-filtered rows instead of the
  // full type-filtered total — the "number moves when you click it" bug — must fail.
  const movingNumber = good.replace(
    "const vendorTotals = useMemo(() => typeFiltered.reduce(addBuckets, emptyBuckets()), [typeFiltered]);",
    "const vendorTotals = useMemo(() => vendorTableRows.reduce(addBuckets, emptyBuckets()), [vendorTableRows]);",
  );
  assert(movingNumber !== good, "selftest: vendorTotals literal not found to mutate — guard regex is stale");
  let movingNumberCaught = false;
  try {
    checkSource(movingNumber, "mut-moving-number");
  } catch {
    movingNumberCaught = true;
  }
  assert(movingNumberCaught, "selftest: expected FAIL when a tile's dollar figure would move when clicked");

  console.log("verify-ap-aging-bucket-filter-tiles --selftest PASS");
}

if (process.argv.includes("--selftest")) {
  try {
    selftest();
  } catch (e) {
    console.error(`verify-ap-aging-bucket-filter-tiles FAIL — ${e.message}`);
    process.exit(1);
  }
} else {
  try {
    checkSource(fs.readFileSync(path.join(ROOT, PAGE), "utf8"));
    checkTestFileExists();
    console.log("verify-ap-aging-bucket-filter-tiles PASS — aging-bucket tiles are click-to-filter, toggle off, and never move their own number");
  } catch (e) {
    console.error(`verify-ap-aging-bucket-filter-tiles FAIL — ${e.message}`);
    process.exit(1);
  }
}
