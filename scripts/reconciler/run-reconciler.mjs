#!/usr/bin/env node
// THE RECONCILER — measurement run. Prints every invariant's exceptions in plain English; with
// --write, publishes the exception queue to docs/reconciliation/exception-queue.{json,md}.
// Exit 1 when any invariant errored (an invariant that cannot run is never reported as clean).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { measureReconciler } from "./measure.mjs";

const LABEL = "run-reconciler";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const QUEUE_JSON = path.join(ROOT, "docs/reconciliation/exception-queue.json");
const QUEUE_MD = path.join(ROOT, "docs/reconciliation/exception-queue.md");

const FIELD_LABELS = {
  unit: "Truck",
  trailer: "Trailer",
  driver: "Driver",
  customer_reference: "Customer W.O. / PO",
  invoice: "Invoice",
};

function money(cents) {
  return cents === null || cents === undefined
    ? ""
    : `$${(cents / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function ageDays(since, asOf) {
  return Math.floor((Date.parse(asOf) - Date.parse(since)) / 86_400_000);
}

function queueDocument(run) {
  const exceptions = run.results
    .flatMap((r) => r.exceptions)
    .map((e) => ({ ...e, age_days: ageDays(e.since, run.ran_at) }))
    .sort((a, b) =>
      a.invariant.localeCompare(b.invariant) ||
      a.entity_label.localeCompare(b.entity_label, undefined, { numeric: true }) ||
      a.field.localeCompare(b.field)
    );
  return {
    _comment:
      "Reconciler exception queue (docs/manuals/03-RULING-THE-RECONCILER-THE-ONE-GENERATIVE-CAUSE.md). Generated by " +
      "scripts/reconciler/run-reconciler.mjs --write against live USMCA, read-only. Every row is a breach no existing " +
      "engine repaired. Do not hand-edit; re-run to refresh.",
    ran_at: run.ran_at,
    operating_company_id: run.operating_company_id,
    invariants: run.results.map((r) => ({
      id: r.invariant,
      title: r.title,
      status: r.status,
      exception_count: r.exceptions.length,
      ...(r.status === "error" ? { error: r.error } : {}),
    })),
    exception_count: exceptions.length,
    exceptions,
  };
}

function queueMarkdown(doc) {
  const lines = [
    "# Reconciler exception queue — USMCA",
    "",
    `As of ${doc.ran_at} (live, read-only). ${doc.exception_count} open exception(s). Generated by ` +
      "`scripts/reconciler/run-reconciler.mjs --write`; do not hand-edit.",
    "",
  ];
  for (const inv of doc.invariants) {
    lines.push(`## ${inv.id} — ${inv.title}`, "");
    if (inv.status === "error") {
      lines.push(`Could not run: ${inv.error}`, "");
      continue;
    }
    const rows = doc.exceptions.filter((e) => e.invariant === inv.id);
    if (rows.length === 0) {
      lines.push("No exceptions.", "");
      continue;
    }
    const withMoney = rows.some((e) => e.amount_cents !== null && e.amount_cents !== undefined);
    lines.push(
      `| Load | Missing | Why it matters |${withMoney ? " Amount |" : ""} Open since | Age (days) | Lane |`,
      `|---|---|---|${withMoney ? "---|" : ""}---|---|---|`
    );
    for (const e of rows) {
      lines.push(
        `| ${e.entity_label} | ${FIELD_LABELS[e.field] ?? e.field} | ${e.reason} |${withMoney ? ` ${money(e.amount_cents)} |` : ""} ` +
          `${e.since.slice(0, 10)} | ${e.age_days} | ${e.owner_seat} |`
      );
    }
    if (withMoney) {
      const total = rows.reduce((n, e) => n + (e.amount_cents ?? 0), 0);
      lines.push("", `Total at stake: ${money(total)}.`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

const run = await measureReconciler({ label: LABEL });
const doc = queueDocument(run);

for (const inv of doc.invariants) {
  if (inv.status === "error") {
    console.error(`${LABEL}: ${inv.id} COULD NOT RUN — ${inv.error}`);
    continue;
  }
  console.log(`${LABEL}: ${inv.id} — ${inv.exception_count} exception(s) — ${inv.title}`);
  for (const e of doc.exceptions.filter((x) => x.invariant === inv.id)) {
    const amount = money(e.amount_cents);
    console.log(
      `  load ${e.entity_label}: ${FIELD_LABELS[e.field] ?? e.field} missing${amount ? ` (${amount})` : ""} — ${e.reason} ` +
        `(open ${e.age_days} day(s), ${e.owner_seat})`
    );
  }
}

if (process.argv.includes("--write")) {
  fs.writeFileSync(QUEUE_JSON, `${JSON.stringify(doc, null, 2)}\n`);
  fs.writeFileSync(QUEUE_MD, `${queueMarkdown(doc)}\n`);
  console.log(`${LABEL}: wrote ${path.relative(ROOT, QUEUE_JSON)} and ${path.relative(ROOT, QUEUE_MD)}`);
}

if (run.errored_invariants.length > 0) process.exit(1);
