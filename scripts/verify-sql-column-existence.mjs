function loadSchema() {
  const raw = JSON.parse(fs.readFileSync(SCHEMA, "utf8"));
  const map = new Map();
  for (const [tbl, cols] of Object.entries(raw.tables ?? {})) {
    map.set(tbl.toLowerCase(), new Set(cols.map((c) => String(c).toLowerCase())));
  }
  return map;
}

function loadAllow() {
  if (!fs.existsSync(ALLOW)) return new Set();
  return new Set(JSON.parse(fs.readFileSync(ALLOW, "utf8")).entries ?? []);
}

function walk(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (e.name.endsWith(".ts") && !e.name.endsWith(".test.ts")) acc.push(p);
  }
  return acc;
}

/**
 * Strip SQL comments before analysis. A column named inside `-- …` or a block comment CANNOT cause
 * 42703 — Postgres never sees it. Leaving them in made this guard flag its own fix notes: when
 * MNT-PHANTOM-02/03 were repaired, the commit left comments explaining the defect
 * ("this summed wl.amount joined on wl.work_order_id", "this matched on li.id"), and the guard kept
 * reporting those very names as live phantoms on fixed code. That is worse than noise — it makes a
 * fixed bug look unfixed, so the allowlist key can never be retired and the backlog never shrinks.
 * `verify-form2290-units-scope` learned the same lesson; this guard had not.
 */
export function stripSqlComments(sql) {
  return sql
    .replace(/\/\*[\s\S]*?\*\//g, " ") // block comments
    .replace(/--[^\n]*/g, " "); // line comments (template literals are multi-line)
}

function extractTemplateLiterals(src) {
  const out = [];
  const re = /`(?:[^`\\]|\\.)*`/gs;
  let m;
  while ((m = re.exec(src))) out.push(stripSqlComments(m[0]));
  return out;
}

/**
 * Analyze one SQL string against the schema. Returns array of {table, column, ctx}.
 * `schema` = Map(table → Set(cols)). Only TARGET_TABLES present in schema are checked.
 */
/**
 * Split a WITH...AS(...) query into per-CTE bodies + the final statement.
 * Each fragment is analyzed with its OWN alias map so rebinding the same alias
 * across CTEs cannot produce cross-CTE false positives (the v1 skip reason).
 * Nested WITH inside a body is handled by recurse in analyzeSql.
 */
export function splitWithQueryFragments(sql) {
  const norm = sql.replace(/\s+/g, " ").trim();
  const low = norm.toLowerCase();
  if (!/\bwith\b[\s\S]*?\bas\s*\(/i.test(low)) return [norm];

  // Find the WITH keyword start (skip leading comments/parens noise — already normalized).
  const withMatch = /\bwith\b/i.exec(low);
  if (!withMatch) return [norm];
  let i = withMatch.index + withMatch[0].length;
  const fragments = [];

  const skipWs = () => { while (i < low.length && /\s/.test(low[i])) i++; };
  const readIdent = () => {
    skipWs();
    const m = /^[a-z_][a-z0-9_]*/i.exec(low.slice(i));
    if (!m) return null;
    i += m[0].length;
    return m[0];
  };

  // Optional RECURSIVE
  skipWs();
  if (low.startsWith("recursive", i)) i += "recursive".length;

  while (i < low.length) {
    const name = readIdent();
    if (!name) break;
    skipWs();
    // optional column list (name1, name2)
    if (low[i] === "(") {
      let depth = 0;
      do {
        if (low[i] === "(") depth++;
        else if (low[i] === ")") depth--;
        i++;
      } while (i < low.length && depth > 0);
      skipWs();
    }
    // AS (
    const asMatch = /^as\s*\(/i.exec(low.slice(i));
    if (!asMatch) break;
    i += asMatch[0].length;
    const bodyStart = i;
    let depth = 1;
    while (i < low.length && depth > 0) {
      const ch = low[i];
      if (ch === "(") depth++;
      else if (ch === ")") depth--;
      i++;
    }
    const bodyEnd = i - 1; // exclusive of closing paren
    fragments.push(norm.slice(bodyStart, bodyEnd));
    skipWs();
    if (low[i] === ",") { i++; continue; }
    break; // final statement follows
  }
  skipWs();
  if (i < norm.length) fragments.push(norm.slice(i));
  return fragments.length ? fragments : [norm];
}

/**
 * Return the SELECT list of a fragment — the text between the leading `SELECT` and its OWN `FROM` —
 * or null when the fragment is not a SELECT.
 *
 * Paren-depth aware, and that is not a nicety: `SELECT EXTRACT(EPOCH FROM created_at) FROM mdata.loads`
 * contains a `FROM` at depth 1 that does NOT end the select list. A naive `indexOf(" from ")` would cut
 * the list at `EPOCH ` and silently drop every projected column after it from analysis.
 */
export function extractSelectList(low) {
  // Lookbehind, not `(^|[\s(])`: extractTemplateLiterals hands us the literal WITH its enclosing
  // backticks, so the real-world string starts "`SELECT …" — no whitespace and no `(` before the
  // keyword. The anchored form matched nothing there, which made this whole pass silently inert on
  // every single-line query in the repo while passing in isolation. Exactly the fake-green shape the
  // guard exists to prevent, so it is asserted in the selftest.
  const m = /(?<![\w.$])select\s+/i.exec(low);
  if (!m) return null;
  let i = m.index + m[0].length;
  // optional DISTINCT / DISTINCT ON (...) / ALL
  const dm = /^(?:distinct(?:\s+on\s*)?|all)\s*/i.exec(low.slice(i));
  if (dm) i += dm[0].length;
  const start = i;
  let depth = 0;
  while (i < low.length) {
    const ch = low[i];
    if (ch === "(") depth++;
    else if (ch === ")") {
      if (depth === 0) break; // fragment ended (we started inside a paren)
      depth--;
    } else if (depth === 0 && /\s/.test(ch) && /^\s+from\s/.test(low.slice(i))) {
      return low.slice(start, i);
    }
    i++;
  }
  return null; // no depth-0 FROM → SELECT with no table; nothing to attribute
}

/**
 * Unqualified column references inside a SELECT list.
 *
 * The gap this closes (CLS-SCHEMA-DRIFT, live 42703 in dispatch/auth-gates/wf-038-active-driver.gate.ts):
 * every unqualified-column pattern above keys on a WHERE/SET/ORDER-BY shape, so a phantom column that is
 * merely PROJECTED was invisible. `SELECT COALESCE(is_dispatch_blocked,false) FROM mdata.drivers` — a
 * column that lives on mdata.UNITS, not mdata.drivers — passed this guard with exit 0 while the endpoint
 * that runs it returned 500 on every call. A phantom column in the SELECT list is exactly as fatal as one
 * in WHERE; only the clause differed. Same lesson the ORDER BY pass learned in 2026-07-25.
 *
 * `AS <alias>` is stripped FIRST because in a select list an alias is a BINDING, not a reference — and
 * the real bug aliases the phantom back to its own name (`COALESCE(is_dispatch_blocked,false) AS
 * is_dispatch_blocked`). Treating select-list aliases as excluded names the way the ORDER BY pass
 * legitimately does would have skipped the very defect this pass exists to catch.
 */
export function unqualifiedSelectListColumns(selectList) {
  const cleaned = stripInterpolations(selectList)
    .replace(/'(?:[^']|'')*'/g, " ") // string literals
    // output-alias BINDINGS (not references). The quoted arm is not optional: the analyzer lowercases
    // the whole statement, so `account_class AS "accountClass"` arrives as `as "accountclass"` and the
    // bare-identifier form does not match past the quote. That left the alias in the stream and it was
    // reported as a phantom `banking.bank_accounts.accountclass` — camelCase aliases are how every
    // route that shapes JSON directly in SQL is written, so this arm is load-bearing, not an edge case.
    .replace(/\bas\s+(?:"[^"]*"|[a-z_][a-z0-9_]*)/gi, " ")
    // Any REMAINING double-quoted identifier is dropped rather than checked. A quoted reference is
    // case-SENSITIVE in Postgres and its true case was already destroyed by the upstream lowercase, so
    // it cannot be matched against the schema without inventing a case. Conservative by construction:
    // this can only skip a check, never invent one.
    .replace(/"[^"]*"/g, " ")
    .replace(/::\s*[a-z_][a-z0-9_]*(?:\s*\[\s*\])?/gi, " ") // casts: status::text
    .replace(/\$\d+/g, " ") // bind params
    .replace(/\b\d+(?:\.\d+)?\b/g, " "); // numeric literals
  const out = [];
  // Unqualified means BOTH sides: not preceded by `.` (it is not the column half of `alias.col`) and
  // not followed by `.` (it is not the QUALIFIER half either). Omitting the second lookahead reported
  // every table alias in the projection as a phantom column — `SELECT c.total FROM …` yielded a
  // "column" named `c` — which is 23 of the 83 raw hits on main, all noise. Function names are
  // excluded by the `(` lookahead.
  const re = /(?<![.\w])([a-z_][a-z0-9_]*)\b(?!\s*[.(])/g;
  let m;
  while ((m = re.exec(cleaned))) out.push(m[1]);
  return out;
}

/**
 * Remove `${…}` template-literal interpolations, brace-depth aware so nested templates
 * (`${cond ? `a` : `b`}`) are excised whole.
 *
 * These are JS, never SQL: an interpolation holds a fragment variable (`${accountSelectCols}`), a
 * conditional, or in a few files an entire nested `await client.query(…)`. Reading their identifiers as
 * column names produced the other large false-positive block on main — `catalogs.accounts.account_select_cols`,
 * `mdata.vendors.vendor_select_columns`, `maintenance.work_orders.await`. Whatever a fragment variable
 * expands to is itself analyzed wherever that fragment is a literal; the placeholder is not.
 */
export function stripInterpolations(s) {
  let out = "";
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "$" && s[i + 1] === "{") {
      let depth = 1;
      i += 2;
      while (i < s.length && depth > 0) {
        if (s[i] === "{") depth++;
        else if (s[i] === "}") depth--;
        i++;
      }
      i--; // loop increment re-advances past the closing brace
      out += " ";
      continue;
    }
    out += s[i];
  }
  return out;
}

export function analyzeSql(sql, schema) {
  const fragments = splitWithQueryFragments(sql);
  // Nested WITH inside a fragment: analyzeSql recurses via split; leaf fragments go to analyzeSqlFragment.
  if (fragments.length > 1 || (fragments.length === 1 && fragments[0] !== sql.replace(/\s+/g, " ").trim() && /\bwith\b[\s\S]*?\bas\s*\(/i.test(fragments[0].toLowerCase()))) {
    const violations = [];
    for (const frag of fragments) {
      // If a fragment itself starts with WITH, recurse; else leaf-analyze.
      if (/\bwith\b[\s\S]*?\bas\s*\(/i.test(frag.toLowerCase()) && splitWithQueryFragments(frag).length > 1) {
        violations.push(...analyzeSql(frag, schema));
      } else {
        violations.push(...analyzeSqlFragment(frag, schema));
      }
    }
    return violations;
  }
  return analyzeSqlFragment(sql, schema);
}

/** Leaf analyzer — never skips on WITH (caller already split). */
function analyzeSqlFragment(sql, schema) {
  const violations = [];
  // ON CONFLICT (...) target columns are STRUCTURALLY UNQUALIFIABLE — Postgres rejects an alias or
  // table prefix inside the conflict target — and they always belong to the INSERT target table, not
  // to whatever table the surrounding fragment happens to reference. Leaving them in made the
  // unqualified-column pass attribute them to the wrong table: it reported
  // accounting.bills.qbo_bill_payment_id for a statement that INSERTs INTO accounting.bill_payments,
  // which is where that column really lives. This was previously invisible because the schema-parity
  // baseline contained a PHANTOM accounting.bills.qbo_bill_payment_id (one of 495 phantom columns the
  // parity DDL parser invented); correcting the baseline exposed the mis-attribution. Excising the
  // conflict target removes an unanalyzable construct — it does not weaken any real check, because
  // every other reference to those columns elsewhere in the statement is still analyzed.
  // Covers BOTH unqualifiable parts: the conflict target list AND the partial-index predicate that may
  // follow it (`ON CONFLICT (...) WHERE col IS NOT NULL DO UPDATE`). The predicate matches the guard's
  // `<col> IS NOT NULL` unqualified pattern exactly, which is how it got attributed to the joined table.
  const withoutConflictTarget = sql.replace(
    /\bon\s+conflict\s*\([^)]*\)(?:\s+where\s+[\s\S]*?)?\s+do\b/gi,
    " ON CONFLICT DO "
  );
  const norm = withoutConflictTarget.replace(/\s+/g, " ").trim();
  const low = norm.toLowerCase();

  // FROM/JOIN <schema.table> [AS] [alias] — build alias→table map.
  const aliasToTable = new Map();
  const tableRefs = [];
  const tableRe = /\b(?:from|join)\s+([a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*)(?:\s+(?:as\s+)?([a-z_][a-z0-9_]*))?/gi;
  let tm;
  while ((tm = tableRe.exec(low))) {
    const table = tm[1];
    const alias = tm[2] && !["on","using","where","left","right","inner","outer","join","cross","full","set"].includes(tm[2])
      ? tm[2] : null;
    tableRefs.push(table);
    if (alias) aliasToTable.set(alias, table);
    // A table with no alias is referable by its bare table name (last segment).
    aliasToTable.set(table.split(".")[1], table);
  }

  const isTarget = (t) => TARGET_TABLES.has(t) && schema.has(t);

  // (1) QUALIFIED refs alias.column — safe even with joins.
  const qualRe = /\b([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\b/gi;
  let qm;
  while ((qm = qualRe.exec(low))) {
    const alias = qm[1];
    const col = qm[2];
    const table = aliasToTable.get(alias);
    if (!table || !isTarget(table)) continue;
    // skip schema.table itself (e.g. mdata.vendors) — alias segment would be a schema, not a col
    if (schema.has(`${alias}.${col}`)) continue;
    if (col === "*") continue;
    if (!schema.get(table).has(col)) {
      violations.push({ table, column: col, ctx: `${alias}.${col}` });
    }
  }

  // (2) UNQUALIFIED columns — ONLY single-target-table literals with no join/subquery/CTE/union.
  const hasSubquery = /\(\s*select\b/i.test(low) || /\bwith\b[\s\S]*\bas\s*\(/i.test(low) || /\bunion\b/i.test(low);
  const distinctTargets = [...new Set(tableRefs.filter(isTarget))];
  const singleTable = tableRefs.length === 1 && distinctTargets.length === 1;
  if (singleTable && !hasSubquery) {
    const table = distinctTargets[0];
    const cols = schema.get(table);
    // Unambiguous column positions: `<col> IS [NOT] NULL`, `<col> <op> ...`, `<col> IN (`, `SET <col> =`.
    // (?<!\.) — a column preceded by a dot is QUALIFIED, not unqualified. `\b` alone matches
    // immediately after the dot, so `de.operating_company_id = $1` was read as a bare
    // `operating_company_id` and attributed to whichever table the fragment's FROM/JOIN named. That
    // is a pure false positive, and it produced one: detention.service.ts was recorded as referencing
    // mdata.load_stops.operating_company_id, a column that file never mentions — the real reference is
    // dispatch.detention_events.operating_company_id on the UPDATE target, whose alias the FROM/JOIN
    // alias map does not collect. This tightens attribution ONLY; every genuinely unqualified column
    // still matches, because a bare column has no preceding dot by definition.
    const patterns = [
      /(?<!\.)\b([a-z_][a-z0-9_]*)\s+is\s+(?:not\s+)?null\b/gi,
      /(?<!\.)\b([a-z_][a-z0-9_]*)\s*(?:=|<>|!=|>=|<=|>|<)\s*(?:\$\d+|'|\d|true|false|now\(\))/gi,
      /(?<!\.)\b([a-z_][a-z0-9_]*)\s+in\s*\(/gi,
      /\bset\s+([a-z_][a-z0-9_]*)\s*=/gi,
    ];
    // ORDER BY / GROUP BY were NOT inspected before 2026-07-25. That blind spot is what let
    // `ORDER BY posted_at` ship against driver_finance.escrow_ledger, whose timestamp is created_at —
    // Postgres 42703, a hard 500 on a live read endpoint, with CI green. A phantom column in ORDER BY
    // is exactly as fatal as one in WHERE; only the clause differed.
    // Handled apart from the patterns above because the clause is a comma-separated LIST whose terms
    // may carry ASC/DESC/NULLS FIRST — a single-capture regex would see only the first column.
    // ORDER BY may legally name a SELECT-list OUTPUT ALIAS rather than a real column —
      // `EXTRACT(...) AS age_days ... ORDER BY age_days` is valid SQL. Collect every `AS <name>` and
      // exclude those, or this check would flag three correct queries (recognition_date,
      // service_location, age_days) and get itself allowlisted into uselessness.
      const outputAliases = new Set();
      for (const am of low.matchAll(/\bas\s+([a-z_][a-z0-9_]*)/gi)) outputAliases.add(am[1]);
      const seenSort = new Set();
    const sortClauseRe = /\b(?:order|group)\s+by\s+([^)]*?)(?:\s+limit\b|\s+offset\b|\s+fetch\b|$)/gi;
    let sc;
    while ((sc = sortClauseRe.exec(low))) {
      for (const raw of sc[1].split(",")) {
        const term = raw.trim().replace(/\s+(asc|desc)\b/g, "").replace(/\s+nulls\s+(first|last)\b/g, "").trim();
        // identifiers only — ordinals (ORDER BY 1), expressions and function calls cannot be resolved
        // to a column by regex and would produce false positives.
        if (!/^[a-z_][a-z0-9_]*$/.test(term)) continue;
        if (SQL_NOISE.has(term) || aliasToTable.has(term) || outputAliases.has(term) || seenSort.has(term)) continue;
        seenSort.add(term);
        if (!cols.has(term)) violations.push({ table, column: term, ctx: `ORDER/GROUP BY ${term}` });
      }
    }
    // SELECT-list unqualified columns — same conservative gate as every other unqualified pass
    // (exactly one target table in the FROM, no join, no subquery/CTE/UNION), so an unqualified name
    // here can only belong to that one table.
    const selectList = extractSelectList(low);
    if (selectList) {
      const seenSel = new Set();
      for (const col of unqualifiedSelectListColumns(selectList)) {
        if (SQL_NOISE.has(col) || aliasToTable.has(col) || seenSel.has(col)) continue;
        seenSel.add(col);
        if (!cols.has(col)) violations.push({ table, column: col, ctx: `SELECT list ${col}` });
      }
    }

    const seen = new Set();
    for (const re of patterns) {
      let m;
      while ((m = re.exec(low))) {
        const col = m[1];
        if (SQL_NOISE.has(col) || aliasToTable.has(col) || seen.has(col)) continue;
        // skip if it's actually a function call `col(` — handled by not matching, but guard anyway
        if (cols.has(col)) { seen.add(col); continue; }
        seen.add(col);
        violations.push({ table, column: col, ctx: `unqualified ${col}` });
      }
    }
  }

  return violations;
}

function runGuard() {
  const schema = loadSchema();
  const allow = loadAllow();
  const found = [];
  for (const file of walk(SRC).sort()) {
    const rel = path.relative(ROOT, file);
    const src = fs.readFileSync(file, "utf8");
    for (const lit of extractTemplateLiterals(src)) {
      const low = lit.toLowerCase();
      if (!/\b(?:from|join|update|into)\s+[a-z_]+\.[a-z_]+/i.test(low)) continue;
      for (const v of analyzeSql(lit, schema)) {
        const key = `${rel}#${v.table}.${v.column}`;
        if (allow.has(key)) continue;
        found.push({ file: rel, ...v, key });
      }
    }
  }

  if (found.length) {
    console.error(
      "verify-sql-column-existence FAILED — SQL references column(s) that do NOT exist on the table " +
        "(the schema-parity baseline is the contract). Fix the column name.\n" +
        "  If the column DOES exist in prod, this is a BASELINE defect — fix it AT SOURCE (the DDL parser " +
        "in scripts/verify-schema-parity.mjs, then regenerate with --update). Do NOT allowlist it: the " +
        "allowlist is a ratchet of REAL defects and its own contract states every key is a live defect " +
        "until removed, so filing a verified-correct reference there mislabels working code as broken " +
        "and hides the baseline drift. (ACCT-F83: this message previously told you to allowlist verified " +
        "false positives, contradicting that contract; the contract is canonical.)\n" +
        "  Offending reference(s):"
    );
    for (const v of found) console.error(`  - ${v.file}: ${v.table}.${v.column}  (${v.ctx})`);
    process.exit(1);
  }
  // Coverage ratchet (systemic-pattern-column-drift-guard): TARGET_TABLES must not shrink.
  const MIN_TARGET_TABLES = 29;
  if (TARGET_TABLES.size < MIN_TARGET_TABLES) {
    console.error(
      `verify-sql-column-existence FAILED — TARGET_TABLES coverage shrank: ${TARGET_TABLES.size} < min ${MIN_TARGET_TABLES}. Ratchet only upward.`
    );
    process.exit(1);
  }
  console.log(`verify-sql-column-existence OK — every checked column on ${TARGET_TABLES.size} curated tables exists in the baseline (min coverage ${MIN_TARGET_TABLES}).`);
}

function selftest() {
  // Minimal in-memory schema mirroring the real #2646 table.
  const schema = new Map([
    ["mdata.vendors", new Set(["id", "operating_company_id", "deactivated_at", "vendor_name"])],
    ["mdata.loads", new Set(["id", "status", "assigned_primary_driver_id", "operating_company_id"])],
  ]);
  let ok = true;
  const check = (name, sql, expectViolation) => {
    const v = analyzeSql(sql, schema);
    const got = v.length > 0;
    const pass = got === expectViolation;
    if (!pass) ok = false;
    console.log(`  ${pass ? "ok  " : "FAIL"} ${name} — ${got ? "flagged " + v.map((x) => x.table + "." + x.column).join(",") : "clean"} (want ${expectViolation ? "flag" : "clean"})`);
  };

  // The actual #2646 bug — phantom voided_at, single-table, in WHERE.
  check("phantom voided_at (unqualified WHERE)",
    "SELECT id FROM mdata.vendors WHERE id = $1 AND operating_company_id = $2 AND voided_at IS NULL LIMIT 1", true);
  // The correct fix must pass.
  check("real deactivated_at (unqualified WHERE)",
    "SELECT id FROM mdata.vendors WHERE id = $1 AND operating_company_id = $2 AND deactivated_at IS NULL LIMIT 1", false);
  // Qualified phantom on a joined target table.
  check("phantom qualified v.voided_at (with join)",
    "SELECT v.id FROM mdata.vendors v JOIN mdata.loads l ON l.id = $1 WHERE v.voided_at IS NULL", true);
  // Qualified real column with join.
  check("real qualified v.deactivated_at (with join)",
    "SELECT v.id FROM mdata.vendors v JOIN mdata.loads l ON l.id = $1 WHERE v.deactivated_at IS NULL", false);
  // Non-target table columns are ignored (no false positive on unknown tables).
  check("non-target table ignored",
    "SELECT foo, bar_nonexistent FROM some.other_table WHERE nope_col IS NULL", false);
  // Function call / expression must not be flagged as a phantom column.
  check("function + real cols not flagged",
    "SELECT id FROM mdata.vendors WHERE lower(vendor_name) = $1 AND deactivated_at IS NULL", false);
  // Subquery literal is skipped for unqualified (too ambiguous) — should stay clean here.
  check("subquery skipped (unqualified not checked)",
    "SELECT id FROM mdata.vendors WHERE id IN (SELECT vendor_id FROM x.y) AND deactivated_at IS NULL", false);

  // CTE fake-green repair (GUARD 2026-07-27): WITH queries must NOT be skipped wholesale.
  check("CTE body phantom qualified column flagged",
    "WITH scoped AS (SELECT v.id FROM mdata.vendors v WHERE v.voided_at IS NULL) SELECT id FROM scoped", true);
  check("CTE body real qualified column clean",
    "WITH scoped AS (SELECT v.id FROM mdata.vendors v WHERE v.deactivated_at IS NULL) SELECT id FROM scoped", false);
  // Alias rebound across CTEs must not false-positive: first CTE uses v=vendors, second uses v as output alias only in FROM scoped.
  check("CTE alias rebind across bodies — no false positive on clean cols",
    "WITH a AS (SELECT v.id FROM mdata.vendors v WHERE v.deactivated_at IS NULL), b AS (SELECT l.id FROM mdata.loads l WHERE l.status = $1) SELECT a.id FROM a JOIN b ON true", false);

  // SELECT-list pass (CLS-SCHEMA-DRIFT). The first case is the VERBATIM live defect from
  // dispatch/auth-gates/wf-038-active-driver.gate.ts, reduced to the vendors fixture: a phantom column
  // projected through COALESCE and aliased back to its own name. This exited 0 before the pass existed.
  check("phantom in SELECT list via COALESCE + self-alias",
    "SELECT status::text, COALESCE(voided_at,false) AS voided_at FROM mdata.vendors WHERE id = $1::uuid LIMIT 1", true);
  check("phantom bare in SELECT list",
    "SELECT id, voided_at FROM mdata.vendors WHERE id = $1", true);
  check("real cols in SELECT list clean",
    "SELECT id, deactivated_at, vendor_name FROM mdata.vendors WHERE id = $1", false);
  // Casts must not be read as columns.
  check("cast type name not flagged as column",
    "SELECT id::text, vendor_name::varchar FROM mdata.vendors WHERE id = $1", false);
  // A depth-1 FROM inside EXTRACT must not truncate the select list — if it did, `voided_at` after it
  // would go unanalyzed and this case would come back clean.
  check("EXTRACT(... FROM ...) does not truncate the select list",
    "SELECT EXTRACT(EPOCH FROM deactivated_at) AS age, voided_at FROM mdata.vendors WHERE id = $1", true);
  check("EXTRACT with only real cols clean",
    "SELECT EXTRACT(EPOCH FROM deactivated_at) AS age, vendor_name FROM mdata.vendors WHERE id = $1", false);
  // Function names and string literals are not columns.
  check("function name + string literal not flagged",
    "SELECT COALESCE(vendor_name, 'unknown_placeholder_col') AS n FROM mdata.vendors WHERE id = $1", false);
  // Output alias of a real expression must not be re-read as a column reference.
  check("output alias binding not treated as a column",
    "SELECT vendor_name AS totally_not_a_column FROM mdata.vendors WHERE id = $1", false);
  // SELECT * must stay clean.
  check("select star clean", "SELECT * FROM mdata.vendors WHERE id = $1", false);
  // Joins still skip the unqualified select-list pass (ambiguous attribution).
  check("join skips unqualified select-list pass",
    "SELECT voided_at FROM mdata.vendors v JOIN mdata.loads l ON l.id = v.id", false);
  // The repo scanner passes the literal WITH its backticks. This case is the reason the select-list
  // pass reported nothing repo-wide on its first cut while every bare-string case above passed.
  check("backtick-delimited literal (as the scanner actually passes it)",
    "`SELECT COALESCE(voided_at,false) AS voided_at FROM mdata.vendors WHERE id = $1`", true);
  // Table aliases in the projection are qualifiers, not columns.
  check("qualified projection through an alias not flagged as a bare column",
    "`SELECT v.vendor_name, v.deactivated_at FROM mdata.vendors v WHERE v.id = $1`", false);
  // JS interpolations are not SQL.
  check("template interpolation is not a column",
    "`SELECT ${vendorSelectColumns}, vendor_name FROM mdata.vendors WHERE id = $1`", false);

  // The two parser gaps the repo-wide run exposed. Both are regressions-in-waiting: each produced a
  // confident, wrong "phantom column" verdict, and a guard that cries wolf is a guard that gets muted.
  // TRIM position keywords (BOTH/LEADING/TRAILING) sit in column position, followed by a literal.
  check("trim(both ' ' from …) — position keyword is not a column",
    "`SELECT trim(both ' ' FROM vendor_name) AS n FROM mdata.vendors WHERE id = $1`", false);
  check("trim(leading/trailing …) — position keywords are not columns",
    "`SELECT trim(leading '0' FROM vendor_name) AS a, trim(trailing ' ' FROM vendor_name) AS b FROM mdata.vendors WHERE id = $1`", false);
  // A camelCase output alias is quoted, and the analyzer has already lowercased the statement.
  check("quoted camelCase output alias is a binding, not a column",
    "`SELECT vendor_name AS \"vendorName\", deactivated_at::text AS \"deactivatedAt\" FROM mdata.vendors WHERE id = $1`", false);
  // The alias arm must not become a blanket amnesty: a phantom column aliased to a quoted name is
  // still a phantom column, because the phantom is on the LEFT of the AS.
  check("phantom column with a quoted alias is still flagged",
    "`SELECT voided_at AS \"voidedAt\" FROM mdata.vendors WHERE id = $1`", true);

  console.log(ok ? "self-test PASS" : "self-test FAIL");
  if (!ok) process.exit(1);
}

