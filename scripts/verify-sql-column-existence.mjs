#!/usr/bin/env node
/**
 * verify-sql-column-existence.mjs  (durable fix for the #2646 phantom-column class)
 *
 * Root cause it prevents: a backend SQL query references a COLUMN that does not exist on the table
 * (e.g. `mdata.vendors.voided_at` — the real column is `deactivated_at`). The phantom-relation guard
 * checks tables/relations, NOT columns, and unit tests that mock `client.query` let the bad SQL ship
 * green — then it 500s (Postgres 42703) on the real path. This guard is the schema-as-contract
 * discipline (QBO/NetSuite/McLeod): every column a query names on a curated high-value table must
 * exist in the prod-derived schema baseline.
 *
 * Scope (v1, deliberately conservative → near-zero false positives):
 *   - Columns are validated ONLY for a curated set of high-value tables (TARGET_TABLES) — the entity,
 *     financial, and dispatch tables where a phantom column is most dangerous.
 *   - QUALIFIED refs `alias.column` are checked whenever `alias` is bound (FROM/JOIN <table> [AS] alias)
 *     to a target table — this is safe even in multi-table joins.
 *   - UNQUALIFIED columns are checked ONLY in single-table literals (exactly one target table in the
 *     FROM, no JOIN, no subquery/CTE/UNION) and ONLY in unambiguous column positions:
 *       `<col> IS [NOT] NULL`, `<col> <op> $n|value`, `<col> IN (...)`, `SET <col> =`.
 *     This is exactly the shape of the #2646 bug (`voided_at IS NULL`) with minimal ambiguity.
 *   - Literals with subqueries/UNION still skip unqualified checks (ambiguous).
 *   - WITH/CTE queries are SPLIT into per-CTE bodies + final statement (each with its own alias
 *     map) — skipping entire WITH queries was a fake-green that hid live 42703s inside CTEs.
 *
 * Column truth = docs/schema-parity-baseline.json (prod-derived, regenerated by verify-schema-parity).
 * An allowlist (BASELINE file) freezes any reviewed false positive so the guard can tighten over time
 * without churn.
 *
 * Usage:
 *   node scripts/verify-sql-column-existence.mjs             # scan
 *   node scripts/verify-sql-column-existence.mjs --selftest  # planted-bug harness (no repo scan)
 */
