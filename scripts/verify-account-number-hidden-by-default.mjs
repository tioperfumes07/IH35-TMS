#!/usr/bin/env node
// ROUND 83 (Lead ruling, 2026-09-22, ~/Downloads/09-22-2026-ALL-SEATS-ROUND-83-ACCOUNT-NUMBERS-HIDDEN-ITEMS-CARRY-QUANTITY.md,
// RULING 1). Owner, verbatim: "I DO NOT LIKE TO SEE THE ACCOUNT NUMBERS SHOWING ANYWHERE.
// AUTOMATICALLY HAVE THEM OFF, IN FILTERS ADD OPTION TO SHOW, BUT I DO NOT WANT TO VIEW THE
// ACCOUNT NUMBERS ANYWHERE."
//
// The canonical helper already exists (owner ruling 2026-07-23):
//   apps/frontend/src/lib/show-account-numbers.ts  -- formatAccountDisplayLabel(), default OFF,
//     localStorage-persisted, cross-tab synced (ih35.showAccountNumbers).
//   apps/frontend/src/lib/useShowAccountNumbers.ts -- the React hook wrapping it.
//   apps/frontend/src/components/parity/referenceOptionLabels.ts -- coaAccountReferenceOption(),
//     the shared picker/dropdown label builder every ReferenceSelect-based account picker should
//     go through.
// Round 83 widens the SURFACE this must hold on from "pickers + a few reports" to EVERY
// account-rendering surface: chart of accounts, JE detail, registers, bills, invoices,
// settlements, load costs, reports, pickers, dropdowns, exports, printed documents.
//
// This guard is the backstop: a file that reads `.account_number` / `.account_code` off an
// account-shaped object OUTSIDE the approved helpers, with no nearby showAccountNumbers gate, is
// a surface that can leak the raw number onto a fresh, toggle-off load -- exactly what the owner
// said he does not want to see. Precision note (same tradeoff every source-text scanner in this
// repo makes): a dot-access to `.account_number`/`.account_code` is not always a *render* -- it
// can be a sort key, an API payload field, a CSV column keyed by name only, etc. This guard
// accepts that some flagged lines are not actual UI leaks (see ALLOWLIST for named, reasoned
// exceptions) in exchange for never silently missing a real one; it is deliberately conservative
// (favors false positives it explains over false negatives it can't see).
//
// SHRINK-ONLY BASELINE RATCHET against
// scripts/verify-account-number-hidden-by-default.baseline.json, same shape as
// verify-dispatch-reads-live-loads-view.mjs:
//   not in baseline, violating                    -> FAIL (new rot)
//   baseline entry got WORSE (more violations)     -> FAIL (debt grew)
//   baseline entry unchanged or better             -> PASS, printed as known debt, never silent
//   baseline entry now CLEAN (file fixed)          -> FAIL "remove me from the baseline"
//
// Static, no DATABASE_URL needed -- pure source-text scan, never reads money data.
export const ALLOW_OFFLINE_SKIP =
  "pure static source-text scan (which .tsx files render .account_number/.account_code outside " +
  "the show-account-numbers helper) -- never connects to a database, so there is nothing to " +
  "silently skip.";

import fs from "node:fs";
import path from "node:path";

const LABEL = "verify-account-number-hidden-by-default";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SRC_DIR = path.join(ROOT, "apps/frontend/src");
const BASELINE_PATH = path.join(ROOT, "scripts/verify-account-number-hidden-by-default.baseline.json");

// Files that ARE the approved helper (they define account_number handling; that's the point).
const HELPER_FILES = new Set([
  "lib/show-account-numbers.ts",
  "lib/useShowAccountNumbers.ts",
  "components/parity/referenceOptionLabels.ts",
]);

// Named, reasoned exceptions: a real `.account_number`/`.account_code` access that is provably
// NOT a render (an API request payload field, a non-display sort/filter key, a type-only re-export).
// Each entry names the file and the reason; adding an entry here requires a reason, not a number.
const ALLOWLIST = new Map([
  [
    "pages/reports/BalanceSheetPage.tsx",
    "the remaining two occurrences (after the Round 83 fix to the three on-screen tables) are " +
      "equality checks against the literal sentinel 'CASH_BASIS_ADJ' to find the synthetic cash-" +
      "basis-adjustment row -- never displayed, never even reaches a gate.",
  ],
  [
    "pages/lists/accounting/AccountDrawer.tsx",
    "the Chart-of-Accounts CREATE/EDIT drawer -- the account_number FIELD ITSELF is what the user " +
      "is directly setting here (Round 83 Ruling 2 approves autogenerated numbers; someone still " +
      "has to be able to see/edit the one they're on). This is the authoring surface, not a list/" +
      "report/picker leak; hiding the number from the admin editing it would make the feature " +
      "impossible to use. Every OTHER surface that merely DISPLAYS an account still goes through " +
      "the toggle.",
  ],
]);

const GUARD_TOKEN_RE = /\.account_(number|code)\b/;
// Lines whose ONLY use of the token is non-display logic -- a React reconciliation `key`/`rowKey`
// prop (never shown to the user), a sort comparator, a search/filter predicate, or a lookup-map
// key. None of these put the number on screen; flagging them would be noise a real reviewer
// would just re-derive by hand every time the guard runs. A line that ALSO renders the value
// (e.g. `render: (line) => line.account_code || "—"`) is not covered by this and still flags.
const LOGIC_ONLY_RE =
  /\bkey=\{|\browKey=|\bsortValue:|\.sort\(|\.localeCompare\(|\.includes\(|\bclassify\(|\beffectiveClass\(|\btoggleClass\(|new Map\(/;
// `showCodes` is the local alias FinancialStatementsPage/BalanceSheetPage/ProfitLossPage/
// TrialBalancePage already bind to useShowAccountNumbers()/getShowAccountNumbers() (owner ruling
// 2026-07-23, pre-dating Round 83) -- a real gate, just a different variable name than the hook.
const GATE_HINT_RE = /formatAccountDisplayLabel|coaAccountReferenceOption|showAccountNumbers|showCodes|getShowAccountNumbers/;

function listTsxFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
      out.push(...listTsxFiles(full));
    } else if (entry.isFile() && (entry.name.endsWith(".tsx") || entry.name.endsWith(".ts"))) {
      if (entry.name.endsWith(".test.tsx") || entry.name.endsWith(".test.ts")) continue;
      if (entry.name.endsWith(".d.ts")) continue;
      out.push(full);
    }
  }
  return out;
}

function loadBaseline() {
  if (!fs.existsSync(BASELINE_PATH)) return null;
  return JSON.parse(fs.readFileSync(BASELINE_PATH, "utf8"));
}

/**
 * Returns violation strings for one file's source text, or [] if clean.
 * A violation is a line matching a `.account_number`/`.account_code` dot-access where neither
 * that line nor the 3 lines above it mentions the approved helper or a showAccountNumbers gate.
 */
export function findViolations(relPath, src) {
  if (HELPER_FILES.has(relPath)) return [];
  const allowReasons = ALLOWLIST.get(relPath);
  const lines = src.split("\n");
  const violations = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (!GUARD_TOKEN_RE.test(line)) continue;
    if (LOGIC_ONLY_RE.test(line)) continue;
    const windowStart = Math.max(0, i - 3);
    const window = lines.slice(windowStart, i + 1).join("\n");
    if (GATE_HINT_RE.test(window)) continue; // gated by the helper or a local showAccountNumbers check
    if (allowReasons) continue; // whole-file allowlist entry (reasoned exception)
    violations.push(`line ${i + 1}: ${line.trim().slice(0, 140)}`);
  }
  return violations;
}

function scan() {
  const files = listTsxFiles(SRC_DIR);
  const byFile = new Map();
  for (const abs of files) {
    const rel = path.relative(SRC_DIR, abs).replace(/\\/g, "/");
    const src = fs.readFileSync(abs, "utf8");
    const violations = findViolations(rel, src);
    if (violations.length > 0) byFile.set(rel, violations);
  }
  return byFile;
}

function run() {
  const found = scan();
  const baseline = loadBaseline();
  let failures = 0;

  if (!baseline) {
    if (found.size > 0) {
      console.error(`${LABEL}: FAIL — no baseline file and ${found.size} file(s) violate. Seed the baseline with a written reason, or fix them.`);
      for (const [f, vs] of found) for (const v of vs) console.error(`  ✗ ${f}: ${v}`);
      failures++;
    }
  } else {
    const baselineNames = new Set(Object.keys(baseline.files || {}));
    const foundNames = new Set(found.keys());

    for (const name of foundNames) {
      if (!baselineNames.has(name)) {
        console.error(`${LABEL}: FAIL — new rot, not in baseline: ${name}`);
        for (const v of found.get(name)) console.error(`  ✗ ${v}`);
        failures++;
      } else {
        const baselineCount = baseline.files[name].count;
        const liveCount = found.get(name).length;
        if (liveCount > baselineCount) {
          console.error(`${LABEL}: FAIL — ${name} got WORSE: baseline ${baselineCount} violation(s), live ${liveCount}`);
          failures++;
        } else {
          console.log(`${LABEL}: known debt — ${name}: ${liveCount} violation(s) (baseline ${baselineCount}, established ${baseline.established})`);
        }
      }
    }
    for (const name of baselineNames) {
      if (!foundNames.has(name)) {
        console.error(`${LABEL}: FAIL — ${name} is now CLEAN — remove it from ${path.basename(BASELINE_PATH)} (shrink the ratchet, don't leave stale debt on the books).`);
        failures++;
      }
    }
  }

  if (failures > 0) process.exit(1);
  console.log(`${LABEL}: PASS — ${found.size} known baselined file(s), 0 new violations.`);
}

function selftest() {
  const checks = [];

  const dirtySrc = `
    function Row({ acct }) {
      return <span>{acct.account_number} {acct.account_name}</span>;
    }
  `;
  checks.push([
    "RED: raw .account_number rendered with no gate -> at least 1 violation",
    findViolations("pages/accounting/SomePage.tsx", dirtySrc).length >= 1,
  ]);

  const cleanSrc = `
    import { formatAccountDisplayLabel } from "../../lib/show-account-numbers";
    function Row({ acct }) {
      const label = formatAccountDisplayLabel(acct);
      return <span>{label}</span>;
    }
  `;
  checks.push([
    "GREEN: rendered through formatAccountDisplayLabel -> 0 violations",
    findViolations("pages/accounting/SomePage.tsx", cleanSrc).length === 0,
  ]);

  const gatedSrc = `
    function Row({ acct, showAccountNumbers }) {
      return <span>{showAccountNumbers ? acct.account_number : ""} {acct.account_name}</span>;
    }
  `;
  checks.push([
    "GREEN: gated behind a local showAccountNumbers check in the same window -> 0 violations",
    findViolations("pages/accounting/SomePage.tsx", gatedSrc).length === 0,
  ]);

  const helperSrc = `
    export function formatAccountDisplayLabel(a) {
      return a.account_number + " " + a.account_name;
    }
  `;
  checks.push([
    "helper file itself is exempt regardless of content",
    findViolations("lib/show-account-numbers.ts", helperSrc).length === 0,
  ]);

  const printSrc = `
    const acctLabel = \`\${acct.account_code ?? ""} \${acct.account_name ?? ""}\`.trim();
  `;
  checks.push([
    "RED (the real AccountRegisterPage.tsx bug shape before the fix): unconditional printed acctLabel -> at least 1 violation",
    findViolations("pages/accounting/AccountRegisterPage.tsx", printSrc).length >= 1,
  ]);

  const logicOnlySrc = `
    const sorted = [...lines].sort((a, b) => String(a.account_code).localeCompare(String(b.account_code)));
    const row = <tr key={\`asset-\${line.account_code}-\${line.account_name}\`}>{line.amount}</tr>;
  `;
  checks.push([
    "GREEN: sort comparator + React key prop, no visible text -> 0 violations",
    findViolations("pages/reports/SomeReport.tsx", logicOnlySrc).length === 0,
  ]);

  const mixedSrc = `
    const cols = [{ key: "account_number", render: (row) => row.account_number ?? "—" }];
  `;
  checks.push([
    "RED: a render callback that returns the raw number, even in a column-def object -> at least 1 violation",
    findViolations("pages/accounting/SomePage.tsx", mixedSrc).length >= 1,
  ]);

  let bad = 0;
  for (const [name, ok] of checks) { if (!ok) bad++; console.log(`${ok ? "ok  " : "FAIL"}  ${name}`); }
  if (bad > 0) {
    console.error(`${LABEL} SELFTEST FAIL — ${bad} check(s) failed`);
    process.exit(1);
  }
  console.log(`${LABEL} SELFTEST PASS`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes("--selftest")) {
    selftest();
  } else {
    run();
  }
}
