/**
 * ROUND 443.22-2c — numbered loan advance note on every funding advance.
 *
 * Owner (2026-10-10): every time we loan to the company it should create a document.
 * Mint runs inside the same create transaction as the advance. A facility with an advance
 * and no note is a defect (guard 18366).
 *
 * Canonical body lives on related_party_loan_entries.note_html (printable without R2).
 * docs.files + docs.file_links file the note both ways (advance + facility). R2 put is
 * best-effort when configured — create never fails closed solely because object storage
 * is offline; the HTML on the entry is the legal note.
 */
import crypto from "node:crypto";
import { isR2Configured, putObjectBytes } from "../../storage/r2-client.js";

type Db = {
  query: (sql: string, values?: unknown[]) => Promise<{ rows: Record<string, unknown>[]; rowCount?: number | null }>;
};

export type AdvanceNoteInput = {
  operatingCompanyId: string;
  loanId: string;
  facilityId: string;
  displayId: string;
  direction: "in" | "out";
  documentKind: string;
  counterpartyName: string | null | undefined;
  relationship: string;
  principalCents: number;
  entryDate: string;
  interestRateBps: number;
  accountId: string;
  actorUserId: string;
};

/** Funding advances that require a note — repayments never mint one. */
export function advanceRequiresNote(args: { direction: "in" | "out"; documentKind: string }): boolean {
  if (args.documentKind === "repayment") return false;
  // Owner wording: "every time we loan to the company" = money IN from the related party.
  return args.direction === "in";
}

function moneyUsd(cents: number): string {
  const sign = cents < 0 ? "-" : "";
  const abs = Math.abs(cents);
  return `${sign}$${(abs / 100).toFixed(2)}`;
}

function aprPct(bps: number): string {
  return `${(bps / 100).toFixed(2)}%`;
}

