function escapeHtml(value: string): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function linkFile(
  client: Db,
  fileId: string,
  entityType: "related_party_loan" | "related_party_loan_facility",
  entityId: string,
  actorUserId: string
): Promise<void> {
  await client.query(
    `INSERT INTO docs.file_links (file_id, entity_type, entity_id, created_by_user_id)
     SELECT $1::uuid, $2, $3::uuid, $4::uuid
      WHERE NOT EXISTS (
        SELECT 1 FROM docs.file_links
         WHERE file_id = $1::uuid AND entity_type = $2 AND entity_id = $3::uuid AND deleted_at IS NULL
      )`,
    [fileId, entityType, entityId, actorUserId]
  );
}

/**
 * Mint the advance note inside the caller's transaction. Returns file id + html.
 * Call only when advanceRequiresNote(...) is true.
 */
export async function mintRelatedPartyLoanAdvanceNote(
  client: Db,
  args: AdvanceNoteInput
): Promise<{ fileId: string; noteHtml: string }> {
  const acct = (
    await client.query(
      `SELECT COALESCE(NULLIF(TRIM(account_number), '') || ' — ', '') || COALESCE(NULLIF(TRIM(account_name), ''), 'Related-party loan')
              AS label
         FROM catalogs.accounts
        WHERE id = $1::uuid AND operating_company_id = $2::uuid
        LIMIT 1`,
      [args.accountId, args.operatingCompanyId]
    )
  ).rows[0];
  const accountLabel = acct?.label ? String(acct.label) : "Related-party loan liability";

  const company = (
    await client.query(
      `SELECT COALESCE(NULLIF(TRIM(legal_name), ''), NULLIF(TRIM(short_name), ''), NULLIF(TRIM(code), ''), 'USMCA Trucking LLC') AS name
         FROM org.companies
        WHERE id = $1::uuid
        LIMIT 1`,
      [args.operatingCompanyId]
    )
  ).rows[0];
  const borrowerName = company?.name ? String(company.name) : "USMCA Trucking LLC";
  const lenderName = (args.counterpartyName && String(args.counterpartyName).trim()) || "Related party";

  const noteHtml = buildAdvanceNoteHtml({
    displayId: args.displayId,
    entryDate: args.entryDate,
    lenderName,
    borrowerName,
    relationship: args.relationship,
    principalCents: args.principalCents,
    interestRateBps: args.interestRateBps,
    accountLabel,
    facilityId: args.facilityId,
  });

  const htmlBuffer = Buffer.from(noteHtml, "utf8");
  const sha256 = crypto.createHash("sha256").update(htmlBuffer).digest("hex");
  const fileUuid = crypto.randomUUID();
  const filename = `loan-advance-note-${args.displayId}.html`;
  const r2Key = `org/${args.operatingCompanyId}/related-party-loan/${args.loanId}/${fileUuid}/${filename}`;

  let uploadCompleted = false;
  if (isR2Configured()) {
    try {
      await putObjectBytes(r2Key, htmlBuffer, "text/html");
      uploadCompleted = true;
    } catch {
      // HTML on the entry remains the note; file row still links for hub navigation.
      uploadCompleted = false;
    }
  }

  const inserted = (
    await client.query(
      `INSERT INTO docs.files (
         id, operating_company_id, original_filename, mime_type, size_bytes, sha256_hash, r2_key,
         upload_completed_at, description, uploader_user_id
       )
       VALUES ($1::uuid, $2::uuid, $3, 'text/html', $4, $5, $6, ${uploadCompleted ? "now()" : "NULL"}, $7, $8::uuid)
       RETURNING id::text`,
      [
        fileUuid,
        args.operatingCompanyId,
        filename,
        htmlBuffer.length,
        sha256,
        r2Key,
        `Related-party loan advance note ${args.displayId}`,
        args.actorUserId,
      ]
    )
  ).rows[0];
  const fileId = String(inserted.id);

  await linkFile(client, fileId, "related_party_loan", args.loanId, args.actorUserId);
  await linkFile(client, fileId, "related_party_loan_facility", args.facilityId, args.actorUserId);

  await client.query(
    `UPDATE accounting.related_party_loan_entries
        SET note_file_id = $1::uuid,
            note_html = $2
      WHERE id = $3::uuid
        AND operating_company_id = $4::uuid`,
    [fileId, noteHtml, args.loanId, args.operatingCompanyId]
  );

  return { fileId, noteHtml };
}
